import 'dotenv/config';
import express from 'express';
import mongoose from 'mongoose';
import cors from 'cors';
import helmet from 'helmet';
import cookieParser from 'cookie-parser';
import rateLimit from 'express-rate-limit';
import authRoutes from './routes/auth.js';
import newsRoutes from './routes/news.js';
const app = express(); app.use(helmet()); app.use(cors({ origin: process.env.CLIENT_ORIGIN, credentials: true })); app.use(express.json({ limit: '20kb' })); app.use(cookieParser()); app.use('/api/auth', rateLimit({ windowMs: 15 * 60 * 1000, max: 80 }), authRoutes); app.use('/api/news', rateLimit({ windowMs: 60 * 1000, max: 60 }), newsRoutes); app.use((err, req, res, next) => { console.error(err); res.status(err.response?.status || 500).json({ message: err.response?.data?.message || 'The server could not complete that request.' }); });
app.get('/', (req, res) => res.json({ name: 'Briefly News API', status: 'ok', endpoints: { news: '/api/news', auth: '/api/auth' } }));
const port = process.env.PORT || 5000;
mongoose.connect(process.env.MONGODB_URI).then(() => app.listen(port, () => console.log(`API listening on ${port}`))).catch(err => { console.error('MongoDB connection failed:', err.message); process.exit(1); });
